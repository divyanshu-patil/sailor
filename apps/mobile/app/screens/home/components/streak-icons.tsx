/**
 * The streak's three faces.
 *
 * A number alone can't say whether a streak is safe, and the copy underneath it
 * is read second. The glyph is read first, so it carries the state:
 *
 *   alive   flame        practised today, or still comfortably inside the day
 *   atRisk  hourglass    today is the last day this streak can be saved
 *   broken  broken heart nothing to lose — the count is zero
 *
 * `hourglass` and `broken_heart` are the designer's own files
 * (assets/images/*.svg), transcribed rather than imported: Metro has no SVG
 * transformer in this app, so an `.svg` is a static asset and not a component.
 * The flame is drawn to match them — one chunky `#462F34` silhouette under the
 * fills — so all three read as one set. Fire colours are deliberately NOT the
 * brand four: a flame in `rose` reads as a balloon, and matching the two
 * supplied assets matters more here than palette purity.
 */
export type StreakStatus = "alive" | "atRisk" | "broken";

/**
 * `atRisk` comes from `streakDeadline` (lib/streak-alarm), which already knows
 * that a streak dies at local midnight of the day after the last completion —
 * this must not re-derive it, or the home screen and the countdown banner can
 * disagree about the same streak.
 */
export function streakStatus(
  streak: StreakState | null,
  atRisk: boolean,
): StreakStatus {
  if (!streak || streak.currentStreak <= 0) return "broken";
  return atRisk ? "atRisk" : "alive";
}

