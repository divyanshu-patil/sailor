/**
 * Optical, not geometric.
 *
 * The three glyphs have very different aspect ratios — the heart is wider than
 * it is tall, the hourglass taller than wide — so drawing them all at the same
 * height makes the heart tower over the number beside it. These factors size
 * each one to the same visual weight.
 */
const OPTICAL: Record<StreakStatus, number> = {
  alive: 1,
  atRisk: 1.02,
  broken: 0.82,
};

export const StreakIcon = memo(function StreakIcon({
  status,
  size,
}: {
  status: StreakStatus;
  size: number;
}) {
  const scaled = size * OPTICAL[status];
  if (status === "atRisk") return <HourglassIcon size={scaled} />;
  if (status === "broken") return <BrokenHeartIcon size={scaled} />;
  return <FlameIcon size={scaled} />;
});
